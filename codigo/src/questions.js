export function questionKey(q) {
  return q.q + ' | ' + q.a.join(' / ');
}

/** Sorteia k perguntas, evitando as já usadas (quando possível). */
export function pickQuestions(k, rng = Math.random, used = new Set()) {
  const fresh = QUESTIONS.filter((q) => !used.has(questionKey(q)));
  const pool = fresh.length >= k ? fresh : QUESTIONS.slice();
  const out = [];
  const idx = pool.map((_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  for (let i = 0; i < k && i < idx.length; i++) out.push(pool[idx[i]]);
  return out;
}
